def rows(table: list[tuple], width: int = 5) -> list[list[tuple]]:
    return [table[i:i + width] for i in range(0, len(table), width)]


def practice_table(table: list[tuple]) -> str:
    return "\n".join("  ".join(f"{h} {k} {r}" for h, k, r, _ in row) for row in rows(table))
