def generate_exam(level: str = "MIXED", count: int = 20, seed: int | None = None) -> list[dict]:
    if level not in {*LEVELS, "MIXED"}:
        raise ValueError(f"Уровень должен быть MIXED или {', '.join(LEVELS)}")
    rng = random.Random(seed)
    if level == "MIXED":
        picked = []
        for i in range(count):
            lv = LEVELS[i % len(LEVELS)]
            picked.append(dict(rng.choice(BANK[lv]), number=i + 1))
    else:
        picked = [dict(rng.choice(BANK[level]), number=i + 1) for i in range(count)]
    return picked


def evaluate(questions: list[dict], answers: dict[str, str] | None) -> dict:
    answers = answers or {}
    correct = 0
    per_level: dict[str, list[int]] = {lv: [0, 0] for lv in LEVELS}
    per_skill: dict[str, list[int]] = {s: [0, 0] for s in SKILLS}
    details = []
    for qst in questions:
        key = str(qst["number"])
        chosen = answers.get(key, "")
        ok = chosen == qst["answer"]
        correct += int(ok)
        lv = per_level.get(qst["level"], [0, 0]); lv[0] += int(ok); lv[1] += 1
        sk = per_skill.get(qst["skill"], [0, 0]); sk[0] += int(ok); sk[1] += 1
        details.append({"number": qst["number"], "level": qst["level"], "skill": qst["skill"],
                        "prompt": qst["prompt"], "answer": qst["answer"], "chosen": chosen,
                        "ok": ok, "explain": qst["explain"], "speak": qst.get("speak", "")})
    total = len(questions)
    pct = round(100 * correct / max(total, 1))
    accuracy = {k: (round(100 * v[0] / v[1]) if v[1] else 0) for k, v in per_skill.items()}
    ranked = sorted(accuracy.items(), key=lambda x: x[1], reverse=True)
    strongest = [x for x in ranked if x[1] > 0][:3] or ranked[:3]
    weakest = sorted(accuracy.items(), key=lambda x: x[1])[:3]
    levels = {k: (round(100 * v[0] / v[1]) if v[1] else None) for k, v in per_level.items()}
    confident = [lv for lv in LEVELS if levels.get(lv) is not None and levels[lv] >= 70]
    estimate = confident[-1] if confident else "N5 и ниже"
    grade = "A" if pct >= 90 else "B" if pct >= 80 else "C" if pct >= 70 else "D" if pct >= 60 else "E"
    advice = {
        "vocab": "Учите слова парами «слово + чтение» в генераторе карточек.",
        "grammar": "Пройдите уроки грамматики соответствующего уровня и закрепите тестом урока.",
        "kanji": "Добавьте проблемные кандзи в рисовалку и повторите он/кун-чтения.",
        "reading": "Читайте короткие предложения вслух и переводите их на русский.",
        "listening": "Используйте аудио-тесты и кнопку озвучки у каждого слова.",
        "syntax": "Собирайте предложения в конструкторе на странице урока.",
    }
    recommendations = [f"{SKILLS[s]} ({pct_s}%): {advice.get(s, '')}" for s, pct_s in weakest]
    return {"total": total, "correct": correct, "percent": pct, "grade": grade,
            "estimate": estimate, "accuracy": accuracy, "levels": levels,
            "weakest": weakest, "strongest": strongest,
            "recommendations": recommendations, "details": details}
